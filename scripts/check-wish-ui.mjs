import { chromium } from 'playwright'
import { mkdir, writeFile } from 'node:fs/promises'
import assert from 'node:assert/strict'
const base='http://127.0.0.1:5187/#/pages/wish/',api='http://127.0.0.1:8087'
const output='../artifacts/wish-ui'
await mkdir(output,{recursive:true})
const browser=await chromium.launch({headless:true,args:['--no-proxy-server']})
const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,timezoneId:'Asia/Shanghai',locale:'zh-CN'})
const page=await context.newPage(),errors=[]
page.on('pageerror',e=>errors.push(e.message))
const login=await (await fetch(api+'/app/auth/wx-login',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({code:'wish-ui-owner-20261108',nickname:'心愿验收用户'})})).json()
assert.equal(login.code,200,login.msg)
await page.addInitScript(token=>localStorage.setItem('kangaroo:app-token',JSON.stringify({type:'string',data:token})),login.token)
async function screen(name){await page.evaluate(()=>window.scrollTo(0,0));await page.waitForTimeout(200);await page.screenshot({path:output+'/'+name+'.png',fullPage:true});const over=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1);assert.equal(over,false,name+' horizontal overflow')}
const input=placeholder=>page.locator('uni-input').filter({has:page.getByText(placeholder,{exact:true})}).locator('input')
await page.goto(base+'index',{waitUntil:'networkidle'})
await page.locator('.wish-search__input input').fill('没有匹配的验收心愿_'+Date.now())
await page.locator('.wish-search__input input').press('Enter')
await page.getByText('这里的心愿，还在路上').waitFor()
await screen('01-square-empty')
await page.getByText('筛选',{exact:true}).click()
await input('输入城市，如广西阳朔').fill('广西')
await page.getByText('免费',{exact:true}).click()
await screen('02-filter')
await page.getByText('查看心愿',{exact:true}).click()
await page.getByText('这里的心愿，还在路上').waitFor()
await page.goto(base+'publish',{waitUntil:'networkidle'})
await input('说说你的小心愿').fill('帮我寄一张阳朔明信片')
await page.locator('textarea').fill('请从阳朔选一张当地风景明信片，写一句祝福后寄往大连，邮费计入成本。')
await input('如辽宁大连').fill('辽宁大连')
await input('如广西阳朔').fill('广西阳朔')
await page.locator('.wp-cost__input input').fill('100')
await page.locator('.wp-cost__input input').blur()
await page.getByText('¥101.00',{exact:true}).waitFor()
await screen('04-paid-publish')
await page.getByText('免费互助',{exact:true}).first().click()
await page.getByText('小小善意，也能跨越山海').waitFor()
await screen('05-free-publish')
await page.goto(base+'rules',{waitUntil:'networkidle'})
await page.getByText('有温度的互助，').waitFor()
await screen('11-rules')
await page.goto(base+'credential',{waitUntil:'networkidle'})
await page.getByText('一份凭证，').waitFor()
await screen('12-credentials')
await page.goto(base+'mine',{waitUntil:'networkidle'})
await page.getByText('还没有这类心愿').waitFor()
await screen('10-mine-empty')
await page.setViewportSize({width:360,height:780})
await page.goto(base+'publish?mode=free',{waitUntil:'networkidle'})
await screen('05-free-360px')
await writeFile(output+'/browser-errors.json',JSON.stringify(errors,null,2))
assert.deepEqual(errors,[])
console.log('Wish UI: empty states, filters, paid/free pricing, rules, credentials and 360/390px layouts passed')
await browser.close()
